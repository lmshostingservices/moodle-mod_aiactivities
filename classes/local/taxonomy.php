    /**
     * Returns the taxonomy for the scenario options.
     *
     * Each entry carries the canonical English value, which is what the
     * generation service is sent, and the translated label shown to the user.
     *
     * @return array[] Array of ['value' => string, 'label' => string, 'sectors' => array[]].
     */
    public static function get_localised(): array {
        static $cache = null;

        if ($cache !== null) {
            return $cache;
        }

        $result = [];

        foreach (self::KEYS as $industry) {
            $sectors = [];
            foreach ($industry['sectors'] as $sector) {
                $sectors[] = self::entry($sector['value'], get_string($sector['key'], 'mod_aiactivities'));
            }

            $entry = self::entry($industry['value'], get_string($industry['industry'], 'mod_aiactivities'));
            $entry['sectors'] = $sectors;
            $result[] = $entry;
        }

        $cache = $result;

        return $result;
    }

    /**
     * Builds one vocabulary entry.
     *
     * The label is omitted when it matches the canonical value, which is the case
     * for all but a couple of entries in English. That roughly halves the size of
     * the list sent to the browser.
     *
     * @param string $value The canonical English value sent to the generation service.
     * @param string $label The translated label shown to the user.
     * @return array The entry.
     */
    private static function entry(string $value, string $label): array {
        $entry = ['value' => $value];
        if ($label !== $value) {
            $entry['label'] = $label;
        }
        return $entry;
    }
